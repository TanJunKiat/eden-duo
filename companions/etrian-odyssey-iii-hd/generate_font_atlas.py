#!/usr/bin/env python3
"""Generate etrian_font_data.h from the OFL Manrope variable font (Pillow required).

Source: https://github.com/google/fonts/tree/main/ofl/manrope
Input SHA-256: 3ae11c49db0455a3cc33e37d380f20fdb8c7f8b41dc07625c177e3d87a9d6ae6
"""
import argparse
from pathlib import Path

# Offline-only dependency; not installed by the emulator or companion build.
from PIL import Image, ImageDraw, ImageFont  # type: ignore[import-not-found]


def generate(source: Path) -> str:
    size = 24
    face = ImageFont.truetype(str(source), size)
    face.set_variation_by_axes([700])
    data = bytearray()
    glyphs = []
    for code in range(32, 256):
        char = bytes([code]).decode("cp1252", errors="replace").replace("\ufffd", "?")
        if code == 127:
            char = "?"
        left, top, right, bottom = face.getbbox(char, anchor="ls")
        w, h = right - left, bottom - top
        glyphs.append((len(data), w, h, round(face.getlength(char) * 16), left, top))
        if w and h:
            glyph = Image.new("L", (w, h))
            ImageDraw.Draw(glyph).text((-left, -top), char, 255, font=face, anchor="ls")
            nibbles = [(v + 8) // 17 for v in glyph.tobytes()]
            nibbles.append(0)
            data.extend(nibbles[i] << 4 | nibbles[i + 1] for i in range(0, w * h, 2))
    if len(data) >= 65536:
        raise ValueError("Glyph atlas exceeds the 16-bit offset range")
    lines = ["// Generated by generate_font_atlas.py. Do not hand edit.",
             "// Copyright 2018 The Manrope Project Authors; SIL OFL 1.1 (dualscreen/licenses).",
             "#pragma once", "#include <cstdint>", "namespace etrian::glass {",
             f"inline constexpr int font_size = {size};",
             "struct Glyph { uint16_t offset; uint8_t width, height; uint16_t advance16; int8_t left, top; };",
             "inline constexpr Glyph glyphs[] = {"]
    lines.extend("    {" + ",".join(map(str, row)) + "}," for row in glyphs)
    lines.extend(["};", "inline constexpr char glyph_alpha[] ="])
    lines.extend('    "' + "".join(f"\\x{b:02x}" for b in data[i : i + 32]) + '"' for i in range(0, len(data), 32))
    return "\n".join(lines + [";", "} // namespace etrian::glass", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("etrian_font_data.h"))
    args = parser.parse_args()
    args.output.write_text(generate(args.font), encoding="utf-8")
